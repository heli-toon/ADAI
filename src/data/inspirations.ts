export const seedInspirations: Inspiration[] = seeds.map((s, i) => {
  const category = categoryById(s.categoryId);
  const created = Date.now() - (seeds.length - i) * 86_400_000;
  return {
    ...s,
    id: `seed-${slugify(s.name)}`,
    slug: slugify(s.name),
    categoryName: category?.name ?? s.categoryId,
    secondaryColors: s.secondaryColors ?? [],
    basePrompt: s.basePrompt ?? (category ? buildBasePrompt(category) : ""),
    createdAt: created,
    updatedAt: created,
  };
});
