export function buildBasePrompt(c: Category): string {
  return [
    `Create a website using the ${c.name.toUpperCase()} design direction.`,
    "",
    "Visual Direction:",
    c.visualCharacteristics,
    "",
    "Typography:",
    c.typographyCharacteristics,
    "",
    "Color System:",
    c.colorCharacteristics,
    "",
    "Layout:",
    c.layoutCharacteristics,
    "",
    "Components:",
    "Build a small reusable set — navigation, hero, content sections, cards, buttons, form controls and footer — all derived from shared design tokens rather than one-off styles.",
    "",
    "Motion:",
    c.motionCharacteristics,
    "",
    "Responsive Behavior:",
    "Design mobile-first. Collapse multi-column layouts to a single column, keep tap targets at least 44px, scale type fluidly and preserve the aesthetic's core cues at every breakpoint.",
    "",
    "Accessibility:",
    "Maintain WCAG AA contrast, visible focus rings, semantic landmarks and headings, labelled controls, and honour prefers-reduced-motion.",
    "",
    "Avoid:",
    c.thingsToAvoid.map((t) => `- ${t}`).join("\n"),
    "",
    `Suggested stack: ${c.technologies.join(", ")}.`,
    `Works well for: ${c.useCases.join(", ")}.`,
    "",
    "Produce original copy, layout and imagery — do not reproduce content from any existing website.",
  ].join("\n");
}

export const categoryById = (id: string) => categories.find((c) => c.id === id);
